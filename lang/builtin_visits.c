/* builtin_visits.c — lume 内建访客统计（嵌入式 DSL 模块）。
 *
 * LUME_VISITS=1（env/.env，LUME_NO_ENV 仍生效）时，引擎启动在入口脚本运行前
 * 加载并执行内嵌的 builtin://visits 模块，自动注册:
 *   POST /api/visit   埋点（body {path,referrer,visitor,ua,wd}）
 *   GET  /api/visits?pin= -> {total,today,uv,days,recent}（PIN 门禁）
 *
 * 契约与各项目独立实现一致（nsbp/specpulse/tnsbp/lume-crm/lume-fastapi-web），
 * 各项目启用时移除自己的 /api/visit + /api/visits 路由即可零代码获得内建版。
 * 未设置 LUME_VISITS 时本模块不加载，现有项目完全不受影响。
 *
 * 配置（env/.env，.env 加载见 main.c lume_load_dotenv）:
 *   VISIT_PIN            owner-only PIN；未配置 /api/visits 一律 403（fail closed）
 *   VISIT_EXCLUDE_IPS    记录时丢弃 + 汇总时过滤（精确 IP / CIDR，逗号分隔）
 *   VISIT_RETENTION_DAYS 保留期（默认 90；<=0 不清理）
 *   VISIT_DB             SQLite 路径（默认 .data/visits.db）
 *
 * 统计口径: 公网真人访问。记录时丢弃自己/排除 IP（隐私：自己访问不落盘）；
 * 汇总时过滤 bot/内网/排除 IP。访问统计是尽力而为，写入失败不阻塞请求。
 *
 * 实现说明: 逻辑留在 Lume DSL（复用各项目已验证的算法），引擎只负责在启动时
 * 注入加载；loader 的内存加载见 loader.c load_module_source()。
 */

#include "lume.h"
#include <stdlib.h>
#include <string.h>

/* LUME_VISITS 开关：任意非 0/off/false 值启用（与 LUME_NO_FS 的开关习惯一致，
 * errs 往"开"的一边）。未设置 -> 关。 */
bool lume_builtin_visits_enabled(void) {
    const char *v = getenv("LUME_VISITS");
    if (!v || !v[0]) return false;
    if (strcmp(v, "0") == 0 || strcmp(v, "off") == 0 ||
        strcmp(v, "false") == 0) return false;
    return true;
}

const char *lume_builtin_visits_src(void) {
    return
"// lume 内建访客统计 — LUME_VISITS=1 时由引擎启动自动加载注册。\n"
"// 契约(与 nsbp/specpulse/tnsbp/lume-crm 一致):\n"
"//   POST /api/visit  body {path,referrer,visitor,ua,wd} -> {ok:{recorded},err}\n"
"//   GET  /api/visits?pin= -> {total,today,uv,days,recent} (PIN 门禁)\n"
"// 配置(env/.env): VISIT_PIN, VISIT_EXCLUDE_IPS, VISIT_RETENTION_DAYS, VISIT_DB\n"
"// 口径: 公网真人。记录时丢弃排除/自己 IP; 汇总时过滤 bot/内网/排除。\n"
"\n"
"let visit_pin = env(\"VISIT_PIN\");\n"
"if (visit_pin == null) { visit_pin = \"\"; }\n"
"let visit_db = env(\"VISIT_DB\");\n"
"if (visit_db == null or visit_db == \"\") { visit_db = \".data/visits.db\"; }\n"
"let visit_retention = 90;\n"
"let _vr = env(\"VISIT_RETENTION_DAYS\");\n"
"if (_vr != null and _vr != \"\") {\n"
"  let n = int(_vr);\n"
"  if (n >= 0 and str(n) == _vr) { visit_retention = n; }\n"
"}\n"
"let visit_last_cleanup = 0;\n"
"\n"
"func env_or(name, d) { let v = env(name); if (v == null) { return d; } return v; }\n"
"func str_or(v, d) { if (v == null) { return d; } let s = str(v); if (s == \"\" or s == \"null\") { return d; } return s; }\n"
"func starts_with(s, p) { return substr(str(s), 0, len(str(p))) == str(p); }\n"
"func as_int(v, d) {\n"
"  if (v == null) { return d; }\n"
"  let s = str(v);\n"
"  if (s == \"\" or s == \"null\") { return d; }\n"
"  let n = try(() => int(s));\n"
"  if (n.ok == null) { return d; }\n"
"  return n.ok;\n"
"}\n"
"func q(sql, params) { let r = try(() => sql_query(visit_db, sql, params)); if (r.ok == null) { return []; } return r.ok; }\n"
"\n"
"// 客户端 IP: X-Forwarded-For 首个（反代），否则 remote_addr。\n"
"func client_ip(req) {\n"
"  let xff = get(req, \"x_forwarded_for\", null);\n"
"  if (xff != null and str(xff) != \"\") {\n"
"    let first = trim(str(get(split(str(xff), \",\"), 0, \"\")));\n"
"    if (first != \"\") { return first; }\n"
"  }\n"
"  return str_or(get(req, \"remote_addr\", \"\"), \"\");\n"
"}\n"
"\n"
"func body_of(req) {\n"
"  let body = get(req, \"body\", null);\n"
"  if (body == null or body == \"\") { return { ok: null, err: \"缺少 body\" }; }\n"
"  let r = try(() => json(body));\n"
"  if (get(r, \"err\", null) != null) { return { ok: null, err: \"body 不是合法 JSON\" }; }\n"
"  return r;\n"
"}\n"
"\n"
"// CIDR / 精确 IP 匹配（八位边界；非整八位向下取整到八位）。\n"
"func ip_match(ip, rule) {\n"
"  let rs = str(rule); let bits = 32;\n"
"  let parts = split(rs, \"/\");\n"
"  if (len(parts) == 2) { bits = int(str(get(parts, 1, \"32\"))); rs = str(get(parts, 0, \"\")); }\n"
"  if (rs == \"\" or bits >= 32) { return ip == rs; }\n"
"  let want = bits / 8;\n"
"  if (want < 1) { return false; }\n"
"  let io = split(ip, \".\"); let ro = split(rs, \".\");\n"
"  if (len(io) != 4 or len(ro) < want) { return false; }\n"
"  for (let i in range(want)) { if (str(io[i]) != str(ro[i])) { return false; } }\n"
"  return true;\n"
"}\n"
"\n"
"func ip_excluded(ip) {\n"
"  if (ip == null or ip == \"\") { return false; }\n"
"  let raw = env_or(\"VISIT_EXCLUDE_IPS\", \"\");\n"
"  if (raw == \"\") { return false; }\n"
"  for (let e in split(replace(str(raw), \" \", \"\"), \",\")) {\n"
"    let rule = str(e);\n"
"    if (rule == \"\" or rule == \"null\") { continue; }\n"
"    if (ip_match(ip, rule)) { return true; }\n"
"  }\n"
"  return false;\n"
"}\n"
"\n"
"// bot / 内网 / 回环：不计入汇总（原始记录保留，便于回溯）。\n"
"func visit_is_bot(ip, ua) {\n"
"  let lua = lower(str_or(ua, \"\"));\n"
"  if (ip == \"\" or ip == \"127.0.0.1\" or ip == \"::1\" or ip == \"0:0:0:0:0:0:0:1\") { return true; }\n"
"  if (starts_with(ip, \"10.\")) { return true; }\n"
"  if (starts_with(ip, \"192.168.\")) { return true; }\n"
"  if (starts_with(ip, \"172.16.\") or starts_with(ip, \"172.17.\") or starts_with(ip, \"172.18.\") or starts_with(ip, \"172.19.\") or starts_with(ip, \"172.30.\") or starts_with(ip, \"172.31.\")) { return true; }\n"
"  if (starts_with(ip, \"169.254.\")) { return true; }\n"
"  let bots = [\"googlebot\",\"bingbot\",\"baiduspider\",\"yandexbot\",\"duckduckbot\",\"petalbot\",\"bytespider\",\"semrushbot\",\"ahrefsbot\",\"mj12bot\",\"sogou\",\"360spider\",\"gptbot\",\"chatgpt\",\"claudebot\",\"facebookexternalhit\",\"whatsapp\",\"telegrambot\",\"zgrab\",\"censys\",\"masscan\",\"nmap\",\"shodan\",\"python-requests\",\"go-http-client\",\"wget\",\"curl\",\"ia_archiver\",\"archive.org_bot\",\"applebot\",\"twitterbot\",\"linkedinbot\",\"pinterest\",\"headlesschrome\",\"urlscan\"];\n"
"  for (let b in bots) { if (contains(lua, str(b))) { return true; } }\n"
"  return false;\n"
"}\n"
"\n"
"func cleanup_visits() {\n"
"  if (visit_retention <= 0) { return; }\n"
"  let cutoff = now() - visit_retention * 86400;\n"
"  let r = try(() => sql_write(visit_db, \"DELETE FROM visits WHERE created < ?\", [cutoff]));\n"
"  if (r.err == null) { visit_last_cleanup = now(); }\n"
"}\n"
"\n"
"func ensure_visits_db() {\n"
"  // 父目录（尽力而为；已存在/只读失败均忽略）。\n"
"  let parts = split(visit_db, \"/\");\n"
"  if (len(parts) >= 2) {\n"
"    let dir = \"\";\n"
"    for (let i in range(len(parts) - 1)) {\n"
"      if (i > 0) { dir = dir + \"/\"; }\n"
"      dir = dir + str(parts[i]);\n"
"    }\n"
"    let m = try(() => mkdir(dir));\n"
"  }\n"
"  // sql_write 的 open 需要文件已存在（只读打开无 CREATE 标志）：只补缺，不覆盖。\n"
"  let existing = try(() => read_file(visit_db));\n"
"  if (existing.ok == null) {\n"
"    let c = try(() => write_file(visit_db, \"\"));\n"
"  }\n"
"  let r = try(() => sql_write(visit_db,\n"
"    \"CREATE TABLE IF NOT EXISTS visits (id INTEGER PRIMARY KEY AUTOINCREMENT, path TEXT, referrer TEXT, ua TEXT, visitor TEXT, ip TEXT, created INTEGER)\"));\n"
"  if (r.err != null) { print(\"builtin visits: 建表失败: \" + r.err); }\n"
"}\n"
"\n"
"post \"/api/visit\", (req) => {\n"
"  let b = body_of(req);\n"
"  let ok = get(b, \"ok\", {});\n"
"  if (ok == null) { ok = {}; }\n"
"  let ip = client_ip(req);\n"
"  // 自己/排除 IP 前置丢弃：不落盘、不计数（隐私，与 nsbp/specpulse 一致）。\n"
"  if (ip == \"\" or ip_excluded(ip)) {\n"
"    return { ok: { recorded: false, excluded: true }, err: null };\n"
"  }\n"
"  let referrer = str(get(ok, \"referrer\", \"\"));\n"
"  referrer = str(get(split(referrer, \"?\"), 0, \"\"));\n"
"  referrer = str(get(split(referrer, \"#\"), 0, \"\"));\n"
"  if (len(referrer) > 200) { referrer = substr(referrer, 0, 200); }\n"
"  let visitor = str(get(ok, \"visitor\", \"anon\"));\n"
"  if (visitor == \"\") { visitor = \"anon\"; }\n"
"  let ua = str(get(ok, \"ua\", \"\"));\n"
"  if (len(ua) > 200) { ua = substr(ua, 0, 200); }\n"
"  let path = str(get(ok, \"path\", \"/\"));\n"
"  if (path == \"\") { path = \"/\"; }\n"
"  // 60s 去重：同 visitor 灌水直接丢弃（防公开端点被刷爆、失真统计）。\n"
"  let since_dupe = now() - 60;\n"
"  let dup = q(\"SELECT COUNT(*) AS n FROM visits WHERE visitor = ? AND created >= ?\", [visitor, since_dupe]);\n"
"  if (as_int(get(get(dup, 0, {}), \"n\", 0), 0) > 0) {\n"
"    return { ok: { recorded: false, deduped: true }, err: null };\n"
"  }\n"
"  if (visit_last_cleanup > 0 and now() - visit_last_cleanup >= 86400) { cleanup_visits(); }\n"
"  let w = try(() => sql_write(visit_db,\n"
"    \"INSERT INTO visits (path, referrer, ua, visitor, ip, created) VALUES (?,?,?,?,?,?)\",\n"
"    [path, referrer, ua, visitor, ip, now()]));\n"
"  if (get(w, \"err\", null) != null) {\n"
"    return { err: get(w, \"err\", \"记录访问失败\") };\n"
"  }\n"
"  return { ok: { recorded: true }, err: null };\n"
"};\n"
"\n"
"get \"/api/visits\", (req) => {\n"
"  // PIN 门禁（fail closed）：未配置 -> 403；?pin= / Bearer 需匹配。\n"
"  if (visit_pin == \"\") {\n"
"    return { status: 403, error: \"访客统计 PIN 未配置 (VISIT_PIN)\" };\n"
"  }\n"
"  let qpin = str(get(get(req, \"query_params\", {}), \"pin\", \"\"));\n"
"  let hpin = \"\";\n"
"  let auth = str(get(req, \"authorization\", \"\"));\n"
"  if (starts_with(lower(auth), \"bearer \")) { hpin = trim(substr(auth, 7)); }\n"
"  if (qpin != visit_pin and hpin != visit_pin) {\n"
"    return { status: 403, error: \"访客统计 PIN 错误\" };\n"
"  }\n"
"\n"
"  // 全量记录（bot / 内网 / 排除在内存过滤；服务数据量小）。\n"
"  let rows = q(\"SELECT ip, path, ua, referrer, visitor, created FROM visits ORDER BY id\", null);\n"
"  let now_ts = now();\n"
"  let today_day = strftime(\"%Y-%m-%d\", now_ts);\n"
"  let since = now_ts - 14 * 86400;\n"
"  let total = 0; let today = 0; let ipset = {};\n"
"  let days = []; let recent = [];\n"
"  for (r in rows) {\n"
"    let ip = str(get(r, \"ip\", \"\"));\n"
"    if (visit_is_bot(ip, str(get(r, \"ua\", \"\")))) { continue; }\n"
"    if (ip_excluded(ip)) { continue; }\n"
"    total = total + 1;\n"
"    put(ipset, ip, 1);\n"
"    let created = as_int(get(r, \"created\", 0), now_ts);\n"
"    let d = strftime(\"%Y-%m-%d\", created);\n"
"    if (d == today_day) { today = today + 1; }\n"
"    let found = false;\n"
"    for (let k in range(len(days))) {\n"
"      if (get(days, k, {}).d == d) {\n"
"        let dd = get(days, k, {});\n"
"        put(dd, \"pv\", get(dd, \"pv\", 0) + 1);\n"
"        put(get(dd, \"uvset\", {}), ip, 1);\n"
"        found = true; break;\n"
"      }\n"
"    }\n"
"    if (not found) {\n"
"      let us = {}; put(us, ip, 1);\n"
"      days = push(days, { d: d, pv: 1, uvset: us });\n"
"    }\n"
"    if (created >= since) {\n"
"      recent = push(recent, {\n"
"        t: strftime(\"%Y-%m-%d %H:%M:%S\", created),\n"
"        ip: ip,\n"
"        path: str(get(r, \"path\", \"/\")),\n"
"        referrer: str(get(r, \"referrer\", \"\")),\n"
"        ua: str(get(r, \"ua\", \"\"))\n"
"      });\n"
"    }\n"
"  }\n"
"  let uv = len(keys(ipset));\n"
"  let days_out = [];\n"
"  for (dd in days) {\n"
"    days_out = push(days_out, { d: get(dd, \"d\", \"\"), pv: get(dd, \"pv\", 0), uv: len(keys(get(dd, \"uvset\", {}))) });\n"
"  }\n"
"  let recent20 = [];\n"
"  let rstart = len(recent) - 20;\n"
"  if (rstart < 0) { rstart = 0; }\n"
"  for (let i in range(rstart, len(recent))) { recent20 = push(recent20, get(recent, i, {})); }\n"
"  // 平铺返回（cicdkit fetchVisits 解码整个 body 交给前端读 total/uv/days/recent）。\n"
"  return { total: total, today: today, uv: uv, days: days_out, recent: recent20 };\n"
"};\n"
"\n"
"// 模块 import 即建表（幂等）。放文件末尾：此时所有函数已定义。\n"
"ensure_visits_db();\n";
}
